"""Measures how well the gap analysis finds biased managers in made-up companies.

Run from the ml/ folder:   python -m sim.evaluate
Writes reports/evaluation.md and reports/evaluation.csv. Takes a few minutes.

Compared on the same companies:
  z-score (FairView)  flag a pair when |z| >= threshold (the manager treats this person
                      differently from his other people, compared with what clients saw)
  naive gap           flag a pair when the average gap is 1 star or more either way
                      (ignores that some managers are strict or generous with everyone)
  Isolation Forest    flag a pair when its pattern score is 0.6 or more
"""
from __future__ import annotations

import csv
import time
from dataclasses import replace
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

from app.analysis import Settings, analyse
from sim.simulate import CompanyConfig, simulate_company

PRODUCT_THRESHOLD = Settings().threshold
PIECES = [5, 10, 15, 20, 30]
BIAS_SIZES = [0.5, 1.0, 1.5]
COMPANIES = 60
SEED = 2026
REPORTS = Path(__file__).resolve().parent.parent / "reports"


def counts(flags: list[bool], truth: list[bool]) -> dict:
    tp = sum(f and t for f, t in zip(flags, truth))
    fp = sum(f and not t for f, t in zip(flags, truth))
    fn = sum(t and not f for f, t in zip(flags, truth))
    tn = sum(not f and not t for f, t in zip(flags, truth))
    nan = float("nan")
    return {
        "precision": tp / (tp + fp) if tp + fp else nan,
        "recall": tp / (tp + fn) if tp + fn else nan,
        "false_alarm_rate": fp / (fp + tn) if fp + tn else nan,
    }


def evaluate(rng: np.random.Generator, cfg: CompanyConfig, threshold: float) -> dict:
    settings = Settings(min_pair=min(10, cfg.pieces_per_employee), min_rest=10, threshold=threshold)
    truth, z_flags, naive_flags, forest_flags, z_abs, forest = [], [], [], [], [], []
    for _ in range(COMPANIES):
        company = simulate_company(rng, cfg)
        for r in analyse(company.pairs, settings):
            if not r["eligible"]:
                continue
            truth.append((r["managerId"], r["employeeId"]) in company.biased)
            z_flags.append(r["flagged"])
            naive_flags.append(abs(r["meanGap"]) >= 1.0)
            forest_flags.append((r["patternScore"] or 0) >= 0.6)
            z_abs.append(abs(r["z"]))
            forest.append(r["patternScore"] or 0)
    out = {"pairs": len(truth), "biased_pairs": sum(truth)}
    for name, flags in [("z", z_flags), ("naive", naive_flags), ("forest", forest_flags)]:
        out.update({f"{name}_{k}": v for k, v in counts(flags, truth).items()})
    out["z_auc"] = roc_auc_score(truth, z_abs)
    out["forest_auc"] = roc_auc_score(truth, forest)
    return out


def pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.0f}%"


def main() -> None:
    start = time.time()
    rng = np.random.default_rng(SEED)
    base = CompanyConfig()
    rows = []

    print("Grid of pieces of work x bias size...")
    for pieces in PIECES:
        for bias in BIAS_SIZES:
            cfg = replace(base, pieces_per_employee=pieces, bias_size=bias)
            rows.append({"table": "grid", "pieces": pieces, "bias": bias, "biased_share": base.biased_share,
                         "threshold": PRODUCT_THRESHOLD, **evaluate(rng, cfg, PRODUCT_THRESHOLD)})
    print("Thresholds...")
    for pieces in [10, 15]:
        for threshold in [2.0, 2.5, 3.0]:
            cfg = replace(base, pieces_per_employee=pieces, bias_size=1.0)
            rows.append({"table": "threshold", "pieces": pieces, "bias": 1.0, "biased_share": base.biased_share,
                         "threshold": threshold, **evaluate(rng, cfg, threshold)})
    print("How common bias is...")
    for share in [0.05, 0.15, 0.30]:
        cfg = replace(base, pieces_per_employee=15, bias_size=1.0, biased_share=share)
        rows.append({"table": "prevalence", "pieces": 15, "bias": 1.0, "biased_share": share,
                     "threshold": PRODUCT_THRESHOLD, **evaluate(rng, cfg, PRODUCT_THRESHOLD)})

    REPORTS.mkdir(exist_ok=True)
    with open(REPORTS / "evaluation.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    (REPORTS / "evaluation.md").write_text(report(rows, base, time.time() - start))
    print(f"Written to {REPORTS / 'evaluation.md'}")


def report(rows: list[dict], cfg: CompanyConfig, seconds: float) -> str:
    grid = [r for r in rows if r["table"] == "grid"]
    thresholds = [r for r in rows if r["table"] == "threshold"]
    prevalence = [r for r in rows if r["table"] == "prevalence"]
    L = [
        "# Gap analysis evaluation (synthetic data)",
        "",
        "Generated by `python -m sim.evaluate`. These are **made-up companies where we know the truth**,",
        "so this shows whether the method works and how to set it, not how it performs on real company data.",
        "",
        "## Set-up",
        "",
        f"- Each row: {COMPANIES} companies, each with {cfg.managers} managers x {cfg.employees_per_manager} employees "
        f"and {cfg.clients_per_manager} clients per manager.",
        f"- {int(cfg.biased_share * 100)}% of manager-employee pairs are biased (half rated up, half rated down), unless the row says otherwise.",
        f"- Rating noise: {cfg.manager_noise} stars for managers, {cfg.client_noise} for clients. Each manager and client is "
        "randomly a little strict or generous. Ratings are rounded to 1-5 stars.",
        f"- FairView settings: |z| >= {PRODUCT_THRESHOLD}, at least 10 rated pieces of work for the pair (or all of them when "
        "the row has fewer), at least 10 for the manager's other employees.",
        f"- Random seed {SEED}, so the numbers are the same on every run.",
        "",
        "**Precision**: of the pairs flagged, the share that were really biased. "
        "**Recall**: of the biased pairs, the share that were flagged. "
        "**False alarms**: of the fair pairs, the share flagged anyway. "
        "**AUC**: how well |z| ranks biased pairs above fair ones (0.5 = coin flip, 1.0 = perfect).",
        "",
        f"## 1. FairView z-score at |z| >= {PRODUCT_THRESHOLD}",
        "",
        "| Rated pieces of work per pair | Bias (stars) | Precision | Recall | False alarms | AUC |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in grid:
        L.append(f"| {r['pieces']} | {r['bias']} | {pct(r['z_precision'])} | {pct(r['z_recall'])} | "
                 f"{pct(r['z_false_alarm_rate'])} | {r['z_auc']:.2f} |")
    L += [
        "",
        "## 2. Choosing the threshold (bias 1 star)",
        "",
        "| Pieces of work per pair | Threshold | Precision | Recall | False alarms |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in thresholds:
        L.append(f"| {r['pieces']} | {r['threshold']} | {pct(r['z_precision'])} | {pct(r['z_recall'])} | {pct(r['z_false_alarm_rate'])} |")
    L += [
        "",
        "## 3. How common bias is (15 pieces of work, bias 1 star)",
        "",
        "When bias is rare, more of the cards are false alarms, even though the false alarm rate stays the same.",
        "",
        "| Biased pairs | Precision | Recall | False alarms |",
        "| --- | --- | --- | --- |",
    ]
    for r in prevalence:
        L.append(f"| {int(r['biased_share'] * 100)}% | {pct(r['z_precision'])} | {pct(r['z_recall'])} | {pct(r['z_false_alarm_rate'])} |")
    L += [
        "",
        "## 4. Compared with simpler methods",
        "",
        "| Pieces | Bias | z-score precision / recall | Naive gap >= 1 star precision / recall | Isolation Forest >= 0.6 precision / recall | Forest AUC |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in grid:
        if r["pieces"] in (10, 15, 20):
            L.append(f"| {r['pieces']} | {r['bias']} | {pct(r['z_precision'])} / {pct(r['z_recall'])} | "
                     f"{pct(r['naive_precision'])} / {pct(r['naive_recall'])} | "
                     f"{pct(r['forest_precision'])} / {pct(r['forest_recall'])} | {r['forest_auc']:.2f} |")
    L += ["", f"_Run time: {seconds:.0f} seconds._", ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
